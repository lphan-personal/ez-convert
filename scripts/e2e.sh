#!/usr/bin/env bash
# Q3 — the end-to-end suite: one automated run per advertised direction.
#
# Builds `e2e/q3/suite.rs` in a throwaway cargo crate (the repo crate itself
# needs GTK/WebKit, which a headless CI box does not have) and runs it against
# the real sidecars. `lofty` is a real dependency here — the audio tag policy is
# half the point of the suite, so it is not stubbed.
#
# Usage:
#   bash scripts/e2e.sh                     # media + documents, non-strict
#   bash scripts/e2e.sh --strict            # any SKIP fails the run
#   bash scripts/e2e.sh --media-only        # skip the LibreOffice leg
#   bash scripts/e2e.sh --docs-only
#   bash scripts/e2e.sh --inject=drop-output  # prove the gate can go red
#
# Engines are the engine layer's own overrides, so this script adds no new
# convention:
#   EZC_VIPS_DIR        dir holding vips + vipsheader            (required)
#   EZC_FFMPEG_DIR      dir holding ffmpeg + ffprobe             (required)
#   EZC_SOFFICE_DIR     dir holding soffice                      (documents)
#   EZC_ENGINE_LIB_DIR  shared libraries for an unpacked vips     (Linux, optional)
#   EZC_VIPS_PLUGIN_DIR dir holding vips-modules-* and libheif/plugins (optional)
#
# Output: a `PASS`/`FAIL`/`SKIP` line per direction, a per-family summary, and
# `report.tsv` / `report.json` / `matrix.md` under `EZC_E2E_REPORT` (default:
# the work dir). Exit code 0 only when every direction this dist can run passed
# and every planted control was caught.
set -euo pipefail

repo_root="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
src="$repo_root/src-tauri/src"
fixtures="${EZC_FIXTURES:-$repo_root/fixtures}"
work="${EZC_E2E_WORK:-${TMPDIR:-/tmp}/ezc-q3-e2e}"
crate_dir="${TMPDIR:-/tmp}/ezc-q3-e2e-crate"
export EZC_E2E_REPORT="${EZC_E2E_REPORT:-$work/report}"

: "${EZC_VIPS_DIR:?set EZC_VIPS_DIR to the directory holding vips and vipsheader}"
: "${EZC_FFMPEG_DIR:?set EZC_FFMPEG_DIR to the directory holding ffmpeg and ffprobe}"

mkdir -p "$crate_dir/src"
cat >"$crate_dir/Cargo.toml" <<'EOF'
[package]
name = "ezc-q3-e2e"
version = "0.0.0"
edition = "2021"
publish = false

[dependencies]
lofty = "0.22"

[workspace]
EOF

# The module tree is the shipped one, included by path: the suite cannot drift
# onto a test copy of the pipeline.
cat >"$crate_dir/src/main.rs" <<EOF
// Generated by scripts/e2e.sh — do not commit.
#![allow(dead_code)]
pub mod model {
    #[path = "$src/model/types.rs"]
    pub mod types;
    #[path = "$src/model/detect.rs"]
    pub mod detect;
    #[path = "$src/model/test_support.rs"]
    pub mod test_support;
    #[path = "$src/model/matrix.rs"]
    pub mod matrix;
}
pub mod engine {
    #[path = "$src/engine/proc.rs"]
    pub mod proc;
    #[path = "$src/engine/stderr_rules.rs"]
    pub mod stderr_rules;
    #[path = "$src/engine/vips.rs"]
    pub mod vips;
    #[path = "$src/engine/ffmpeg.rs"]
    pub mod ffmpeg;
    #[path = "$src/engine/plan.rs"]
    pub mod plan;
    #[path = "$src/engine/soffice.rs"]
    pub mod soffice;
    #[path = "$src/engine/verify.rs"]
    pub mod verify;
    #[path = "$src/engine/doc.rs"]
    pub mod doc;
    #[path = "$src/engine/tags.rs"]
    pub mod tags;
    #[path = "$src/engine/convert.rs"]
    pub mod convert;
}
#[path = "$repo_root/e2e/q3/suite.rs"]
pub mod q3;

fn main() {
    q3::run();
}
EOF

export PATH="$HOME/.cargo/bin:$PATH"
mkdir -p "$work"
cd "$crate_dir"
if ! cargo build --quiet --offline 2>/dev/null; then
  cargo build --quiet
fi
exec ./target/debug/ezc-q3-e2e "$fixtures" "$work" "$@"
