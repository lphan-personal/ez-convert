#!/usr/bin/env bash
# Run the detection/matrix tests without cargo and without GTK/WebKit.
#
# Why this exists: `src-tauri` depends on Tauri, whose Linux build needs
# GTK/WebKit dev packages, and `model/settings.rs` uses serde. A dev box or a
# container without those cannot run `cargo test` at all — but the detection core
# (`types.rs`, `detect.rs`, `matrix.rs`) is std-only by construction
# (ARCHITECTURE.md §2.2), so it compiles as its own crate root with plain rustc.
# Same files, same test functions, no shell and no third-party crate.
#
# CI runs the authoritative `cargo test`; this is the local/offline path and the
# proof that the core really is shell-independent.
#
# Usage: scripts/test-model.sh [--test-threads=1]
set -euo pipefail

repo_root="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
model_dir="$repo_root/src-tauri/src/model"
work="${TMPDIR:-/tmp}/ezc-model-tests.$$"
mkdir -p "$work"

harness="$work/harness.rs"
cat >"$harness" <<EOF
// Generated by scripts/test-model.sh — do not commit.
// Compiles exactly the std-only detection core, so it runs where the Tauri shell
// cannot (no GTK/WebKit, no serde).
#[path = "$model_dir/types.rs"]
pub mod types;
#[path = "$model_dir/detect.rs"]
pub mod detect;
#[path = "$model_dir/matrix.rs"]
pub mod matrix;
#[path = "$model_dir/test_support.rs"]
pub mod test_support;
EOF

# EZC_REPO_ROOT is read at COMPILE time by test_support (option_env!), which is
# how the harness finds fixtures/ and docs/ outside cargo.
EZC_REPO_ROOT="$repo_root" rustc --edition 2021 --test -o "$work/model-tests" "$harness"

"$work/model-tests" "$@"
