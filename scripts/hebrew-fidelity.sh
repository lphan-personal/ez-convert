#!/usr/bin/env bash
# Card t_76ca844f — Hebrew fidelity after the Culmus strip, measured through the
# shipped document pipeline.
#
# Converts `evidence/fixtures/hebrew-clm-ctl.docx` (five paragraphs naming the
# five stripped Culmus families, in the `cs` slot a Hebrew document uses) with
# `engine::doc::convert`, then reads back the fonts the PDF embeds. Pass when the
# five OFL twins are in the PDF and the fallbacks are not.
#
# Why a fixture document and not the ODF one: `hebrew-clm.fodt` sets
# `style:font-name` only, which LibreOffice applies to the *Western* slot — its
# Hebrew runs resolve through the document's CTL default and never touched the
# Culmus faces, so it cannot show a substitution (evidence §2). The .docx carries
# `w:rFonts … w:cs="<family>"`, which is what a Hebrew document actually stores.
#
# Usage:
#   bash scripts/hebrew-fidelity.sh <stripped-pack-dir>       # program/ dir or pack root
#   EZC_SOFFICE_DIR=… bash scripts/hebrew-fidelity.sh         # same, from env
#
# The pack must already have `scripts/strip-engine-pack.py` applied: this script
# asserts the twins *replace* the stripped families, so a pack that still carries
# DavidCLM.otf proves nothing (LibreOffice prefers the real thing) — it would pass
# with the wrong mechanism. The check refuses that case explicitly.
set -euo pipefail

repo_root="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
src="$repo_root/src-tauri/src"
work="${EZC_HEBREW_WORK:-${TMPDIR:-/tmp}/ezc-hebrew-$$}"
fixture="$repo_root/evidence/fixtures/hebrew-clm-ctl.docx"

pack="${1:-${EZC_SOFFICE_DIR:-}}"
if [ -z "$pack" ]; then
  echo "usage: bash scripts/hebrew-fidelity.sh <pack-dir>  (or set EZC_SOFFICE_DIR)" >&2
  exit 2
fi
if [ -d "$pack/program" ]; then
  export EZC_SOFFICE_DIR="$(cd "$pack/program" && pwd)"
else
  export EZC_SOFFICE_DIR="$(cd "$pack" && pwd)"
fi
# The Linux pack's own shared libraries (libXinerama and friends); the engine
# layer scrubs the child environment, so this is the supported channel.
: "${EZC_ENGINE_LIB_DIR:=$repo_root/../vendor/lo-deps/usr/lib/x86_64-linux-gnu}"
export EZC_ENGINE_LIB_DIR

pack_root="$(cd "$EZC_SOFFICE_DIR/.." && pwd)"
stripped_fonts=$(find "$pack_root/share/fonts/truetype" -iname "*CLM*" 2>/dev/null | wc -l)
echo "pack:            $pack_root"
echo "culmus files:    $stripped_fonts (must be 0)"
if [ "$stripped_fonts" -ne 0 ]; then
  echo "FAIL  the pack still carries Culmus fonts — run scripts/strip-engine-pack.py first" >&2
  exit 1
fi

mkdir -p "$work"
harness="$work/main.rs"
cat >"$harness" <<EOF
// Generated by scripts/hebrew-fidelity.sh — do not commit.
#![allow(dead_code)]
pub mod model {
    #[path = "$src/model/types.rs"]
    pub mod types;
    #[path = "$src/model/detect.rs"]
    pub mod detect;
    #[path = "$src/model/test_support.rs"]
    pub mod test_support;
    #[path = "$src/model/matrix.rs"]
    pub mod matrix;
}
pub mod engine {
    #[path = "$src/engine/proc.rs"]
    pub mod proc;
    #[path = "$src/engine/stderr_rules.rs"]
    pub mod stderr_rules;
    #[path = "$src/engine/vips.rs"]
    pub mod vips;
    #[path = "$src/engine/ffmpeg.rs"]
    pub mod ffmpeg;
    #[path = "$src/engine/plan.rs"]
    pub mod plan;
    #[path = "$src/engine/soffice.rs"]
    pub mod soffice;
    #[path = "$src/engine/verify.rs"]
    pub mod verify;
    #[path = "$src/engine/doc.rs"]
    pub mod doc;
}
#[path = "$repo_root/e2e/hebrew/driver.rs"]
pub mod driver;

fn main() {
    std::process::exit(driver::run());
}
EOF

export PATH="$HOME/.cargo/bin:$PATH"
if ! rustc --edition 2021 -o "$work/hebrew-fidelity" "$harness" 2>"$work/rustc.log"; then
  echo "FAIL  the driver did not compile:" >&2
  cat "$work/rustc.log" >&2
  exit 1
fi

echo "--- convert (engine::doc::convert, Docx -> Pdf)"
"$work/hebrew-fidelity" "$fixture" "$work"

pdf="$work/hebrew-clm.pdf"
if [ ! -s "$pdf" ]; then
  echo "FAIL  no PDF was produced" >&2
  exit 1
fi

echo "--- /BaseFont in the produced PDF"
fonts=$(grep -a -o "/BaseFont */[A-Za-z0-9+#-]*" "$pdf" | sed 's|.*/||' | sort -u)
echo "$fonts" | sed 's/^/    /'

status=0
for twin in DavidLibre- FrankRuhlHofshi- MiriamLibre- LiberationMono Alef-; do
  if echo "$fonts" | grep -q -- "$twin"; then
    echo "PASS  $twin present"
  else
    echo "FAIL  $twin missing — the substitution did not take effect" >&2
    status=1
  fi
done
for fallback in NotoSerif-Regular LinuxLibertine NotoSans-Regular DejaVuSansMono; do
  if echo "$fonts" | grep -q -- "$fallback"; then
    echo "FAIL  $fallback still embedded — a paragraph fell through to the fallback chain" >&2
    status=1
  fi
done

if [ "$status" -eq 0 ]; then
  echo "RESULT PASS  the five twins replace the stripped families in the PDF"
else
  echo "RESULT FAIL  see the lines above" >&2
fi
exit "$status"
