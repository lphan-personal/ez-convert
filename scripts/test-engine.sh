#!/usr/bin/env bash
# Run the engine-layer tests without cargo, without GTK/WebKit and without the
# network.
#
# Why this exists: `src-tauri` depends on Tauri, whose Linux build needs
# GTK/WebKit dev packages. The engine layer itself is std-only by construction
# (ARCHITECTURE.md §2.2) — one exception: `engine/tags.rs` uses the `lofty`
# crate, so this harness substitutes a stub for it and tags.rs is proven by
# `spikes/c2/harness` (real lofty, real files) instead.
#
# Usage: scripts/test-engine.sh [--test-threads=1]
set -euo pipefail

repo_root="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
src="$repo_root/src-tauri/src"
work="${TMPDIR:-/tmp}/ezc-engine-tests.$$"
mkdir -p "$work"

harness="$work/harness.rs"
cat >"$harness" <<EOF
// Generated by scripts/test-engine.sh — do not commit.
#![allow(dead_code)]
pub mod model {
    #[path = "$src/model/types.rs"]
    pub mod types;
    #[path = "$src/model/detect.rs"]
    pub mod detect;
    #[path = "$src/model/test_support.rs"]
    pub mod test_support;
    #[path = "$src/model/matrix.rs"]
    pub mod matrix;
}
pub mod engine {
    #[path = "$src/engine/proc.rs"]
    pub mod proc;
    #[path = "$src/engine/stderr_rules.rs"]
    pub mod stderr_rules;
    #[path = "$src/engine/vips.rs"]
    pub mod vips;
    #[path = "$src/engine/ffmpeg.rs"]
    pub mod ffmpeg;
    #[path = "$src/engine/plan.rs"]
    pub mod plan;
    #[path = "$src/engine/verify.rs"]
    pub mod verify;
    #[path = "$src/engine/convert.rs"]
    pub mod convert;
    // Stub: the real module is proven by spikes/c2/harness with the real crate.
    pub mod tags {
        use std::path::Path;
        #[derive(Debug, Clone, PartialEq, Eq)]
        pub struct MergeReport {
            pub items: usize,
            pub pictures: usize,
            pub tag_type: Option<()>,
            pub source_untagged: bool,
        }
        #[derive(Debug, Clone, PartialEq, Eq)]
        pub enum TagError {
            Unavailable,
        }
        impl std::fmt::Display for TagError {
            fn fmt(&self, f: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
                write!(f, "lofty not linked in this harness")
            }
        }
        pub fn merge(_from: &Path, _to: &Path) -> Result<MergeReport, TagError> {
            Err(TagError::Unavailable)
        }
    }
}
EOF

# EZC_REPO_ROOT is read at COMPILE time by the tests that walk the tree.
EZC_REPO_ROOT="$repo_root" rustc --edition 2021 --test -o "$work/engine-tests" "$harness"
"$work/engine-tests" "$@"
