#!/usr/bin/env bash
# Run the C4 unit tests AND the C4 end-to-end matrix locally, without cargo in
# the app crate.
#
# Why: `src-tauri` depends on Tauri, whose Linux build needs GTK/WebKit dev
# packages that are not installed on this host, so `cargo test` cannot build the
# real crate here. The modules under test are Tauri-free by construction
# (ARCHITECTURE.md §2.1), so this script generates a throwaway cargo package in
# the temp dir that compiles exactly those source files by absolute path, and runs
# their tests plus the e2e file against the real engine.
#
# Two legs:
#   unit — job::hash / job::publish / job::journal / job::outputs (+ the existing
#          model and queue suites, which share the module graph)
#   e2e  — spikes/c4/e2e.rs against the real ffmpeg (needs ffmpeg + ffprobe)
#
# Usage:
#   scripts/c4-tests.sh              # unit + e2e
#   scripts/c4-tests.sh --unit-only  # skip the engine leg
#
# Environment:
#   EZC_FFMPEG_DIR   directory holding ffmpeg/ffprobe (default: /usr/local/bin)
#   CARGO            cargo binary (default: $HOME/.cargo/bin/cargo or `cargo`)
#
# CI runs the same #[cfg(test)] modules through `cargo test` on three platforms;
# this script is the local, no-GTK path (and the only one that runs the e2e here).
set -euo pipefail

repo_root="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
src="$repo_root/src-tauri/src"
fixtures="$repo_root/fixtures"
unit_only=0
e2e_only=0
for arg in "$@"; do
  case "$arg" in
    --unit-only) unit_only=1 ;;
    --e2e-only) e2e_only=1 ;;
    *) echo "unknown argument: $arg" >&2; exit 2 ;;
  esac
done

cargo_bin="${CARGO:-}"
if [ -z "$cargo_bin" ]; then
  if [ -x "$HOME/.cargo/bin/cargo" ]; then
    cargo_bin="$HOME/.cargo/bin/cargo"
  else
    cargo_bin="cargo"
  fi
fi

work="${TMPDIR:-/tmp}/ezc-c4-tests.$$"
mkdir -p "$work/src" "$work/tests"
trap 'rm -rf "$work"' EXIT

cat >"$work/Cargo.toml" <<TOML
[package]
name = "ezc-c4-e2e"
version = "0.0.0"
edition = "2021"
publish = false

[dependencies]
serde = { version = "1", features = ["derive"] }
serde_json = "1"
sha2 = "0.10"
lofty = "0.22"
TOML

cat >"$work/src/lib.rs" <<EOF
//! Generated by scripts/c4-tests.sh — do not commit.
//!
//! Compiles the repo's Tauri-free modules by absolute path so their own
//! \`#[cfg(test)]\` suites run against the real dependency set.
#![allow(dead_code)]

pub mod model {
    #[path = "$src/model/types.rs"]
    pub mod types;
    #[path = "$src/model/detect.rs"]
    pub mod detect;
    #[path = "$src/model/matrix.rs"]
    pub mod matrix;
    #[path = "$src/model/settings.rs"]
    pub mod settings;
    #[path = "$src/model/naming.rs"]
    pub mod naming;
    #[cfg(test)]
    #[path = "$src/model/test_support.rs"]
    pub mod test_support;
}

pub mod engine {
    #[path = "$src/engine/proc.rs"]
    pub mod proc;
    #[path = "$src/engine/stderr_rules.rs"]
    pub mod stderr_rules;
    #[path = "$src/engine/vips.rs"]
    pub mod vips;
    #[path = "$src/engine/ffmpeg.rs"]
    pub mod ffmpeg;
    #[path = "$src/engine/plan.rs"]
    pub mod plan;
    #[path = "$src/engine/soffice.rs"]
    pub mod soffice;
    #[path = "$src/engine/verify.rs"]
    pub mod verify;
    #[path = "$src/engine/convert.rs"]
    pub mod convert;
    #[path = "$src/engine/doc.rs"]
    pub mod doc;
    #[path = "$src/engine/tags.rs"]
    pub mod tags;
}

pub mod job {
    #[path = "$src/job/paths.rs"]
    pub mod paths;
    #[path = "$src/job/hash.rs"]
    pub mod hash;
    #[path = "$src/job/publish.rs"]
    pub mod publish;
    #[path = "$src/job/journal.rs"]
    pub mod journal;
    #[path = "$src/job/queue.rs"]
    pub mod queue;
    #[path = "$src/job/outputs.rs"]
    pub mod outputs;
}
EOF

# The model tests locate fixtures/docs/evidence from the repo root at compile
# time (see model/test_support.rs).
export EZC_REPO_ROOT="$repo_root"
export EZC_FFMPEG_DIR="${EZC_FFMPEG_DIR:-/usr/local/bin}"

cd "$work"
echo "--- building ($cargo_bin, offline) ---"
"$cargo_bin" build --offline --quiet

echo "--- unit leg: model + job suites ---"
if [ "$e2e_only" -eq 0 ]; then
  "$cargo_bin" test --offline --lib --quiet
fi

if [ "$unit_only" -eq 1 ]; then
  exit 0
fi

cat >"$work/tests/e2e.rs" <<EOF
//! Generated by scripts/c4-tests.sh — includes the committed e2e scenario.
include!("$repo_root/spikes/c4/e2e.rs");
EOF

echo "--- e2e leg: real ffmpeg ---"
EZC_FIXTURES="$fixtures" EZC_WORK="$work/e2e-work" \
  "$cargo_bin" test --offline --test e2e -- --nocapture --test-threads=1
