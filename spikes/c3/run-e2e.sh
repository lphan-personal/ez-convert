#!/usr/bin/env bash
# Build and run the C3 document end-to-end matrix.
#
# Two legs, one harness:
#   linux   — rustc against the vendored TDF LibreOffice tree on this box
#   windows — the SAME Rust code cross-compiled to x86_64-pc-windows-gnu and run
#             on the win11-dev VM against the installed LibreOffice 26.8.2.2
#
# The repo crate cannot be built here (Tauri needs GTK/WebKit), so this wraps the
# engine layer in a throwaway rustc harness, exactly like scripts/test-engine.sh.
#
# Usage:
#   spikes/c3/run-e2e.sh                       # linux leg
#   spikes/c3/run-e2e.sh --windows              # windows leg (cross-build + ssh)
#   spikes/c3/run-e2e.sh --measure-legacy       # also measure unproven directions
#
# Environment:
#   EZC_SOFFICE_DIR     Linux: program/ of a LibreOffice tree
#                       (default: the vendored 26.8.2 tree)
#   EZC_ENGINE_LIB_DIR  Linux: shared libs for that unpacked tree
#   MINGW_BIN           Windows cross-build: dir holding x86_64-w64-mingw32-gcc
#   WIN_HOST / WIN_KEY  ssh target + key for the Windows leg
set -euo pipefail

repo_root="$(cd "$(dirname "${BASH_SOURCE[0]}")/../.." && pwd)"
src="$repo_root/src-tauri/src"
fixtures="$repo_root/fixtures"
leg="${LEG:-linux}"
args=()
for a in "$@"; do
  case "$a" in
    --windows) leg="windows" ;;
    --linux) leg="linux" ;;
    --measure-legacy) args+=("$a") ;;
    *) args+=("$a") ;;
  esac
done

export PATH="$HOME/.cargo/bin:$PATH"

work="${TMPDIR:-/tmp}/ezc-c3-e2e.$$"
mkdir -p "$work"
harness="$work/main.rs"
trap 'rm -rf "$work"' EXIT

cat >"$harness" <<EOF
// Generated by spikes/c3/run-e2e.sh — do not commit.
#![allow(dead_code)]
pub mod model {
    #[path = "$src/model/types.rs"]
    pub mod types;
    #[path = "$src/model/detect.rs"]
    pub mod detect;
    #[path = "$src/model/test_support.rs"]
    pub mod test_support;
    #[path = "$src/model/matrix.rs"]
    pub mod matrix;
}
pub mod engine {
    #[path = "$src/engine/proc.rs"]
    pub mod proc;
    #[path = "$src/engine/stderr_rules.rs"]
    pub mod stderr_rules;
    #[path = "$src/engine/vips.rs"]
    pub mod vips;
    #[path = "$src/engine/ffmpeg.rs"]
    pub mod ffmpeg;
    #[path = "$src/engine/plan.rs"]
    pub mod plan;
    #[path = "$src/engine/soffice.rs"]
    pub mod soffice;
    #[path = "$src/engine/verify.rs"]
    pub mod verify;
    #[path = "$src/engine/doc.rs"]
    pub mod doc;
    #[path = "$src/engine/convert.rs"]
    pub mod convert;
    // The document matrix never touches tags; stub keeps convert.rs compiling.
    pub mod tags {
        use std::path::Path;
        #[derive(Debug, Clone, PartialEq, Eq)]
        pub struct MergeReport {
            pub items: usize,
            pub pictures: usize,
            pub tag_type: Option<()>,
            pub source_untagged: bool,
        }
        #[derive(Debug, Clone, PartialEq, Eq)]
        pub enum TagError {
            Unavailable,
        }
        impl std::fmt::Display for TagError {
            fn fmt(&self, f: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
                write!(f, "lofty not linked in this harness")
            }
        }
        pub fn merge(_from: &Path, _to: &Path) -> Result<MergeReport, TagError> {
            Err(TagError::Unavailable)
        }
    }
}
include!("$repo_root/spikes/c3/e2e.rs");
EOF

run_linux() {
  : "${EZC_SOFFICE_DIR:=/opt/data/converter/vendor/libreoffice-26.8.2/opt/libreoffice26.8/program}"
  : "${EZC_ENGINE_LIB_DIR:=/opt/data/converter/vendor/lo-deps/usr/lib/x86_64-linux-gnu}"
  export EZC_ENGINE_LIB_DIR
  rustc --edition 2021 -O -o "$work/ezc-c3-e2e" "$harness"
  echo "--- linux leg ---"
  "$work/ezc-c3-e2e" "$fixtures" "$work/linux" \
    "--soffice-dir=$EZC_SOFFICE_DIR" "${args[@]}"
}

run_windows() {
  local host="${WIN_HOST:-ryo@10.0.0.191}"
  local key="${WIN_KEY:-/opt/data/.ssh/win11-dev}"
  # A *Linux-hosted* mingw cross toolchain (the winlibs zip is a Windows-hosted
  # toolchain and cannot run here). Fetch once with:
  #   curl -sSL https://musl.cc/x86_64-w64-mingw32-cross.tgz | tar -xz -C <dir>
  local mingw="${MINGW_BIN:-/opt/data/profiles/wright/cache/scratch/mingw-cross/x86_64-w64-mingw32-cross/bin}"
  if [ ! -x "$mingw/x86_64-w64-mingw32-gcc" ]; then
    echo "no Linux-hosted mingw at $mingw — set MINGW_BIN or fetch the toolchain (see comment)" >&2
    exit 2
  fi
  export PATH="$mingw:$PATH"
  rustc --edition 2021 -O --target x86_64-pc-windows-gnu \
    -C linker=x86_64-w64-mingw32-gcc -o "$work/ezc-c3-e2e.exe" "$harness"
  ls -la "$work/ezc-c3-e2e.exe"

  local ssh_opts=(-i "$key" -o StrictHostKeyChecking=no -o BatchMode=yes)
  ssh "${ssh_opts[@]}" "$host" 'if not exist C:\ezc mkdir C:\ezc' >/dev/null 2>&1 || true
  scp "${ssh_opts[@]}" "$work/ezc-c3-e2e.exe" "$host:C:/ezc/ezc-c3-e2e.exe"
  tar -C "$(dirname "$fixtures")" -cf - "$(basename "$fixtures")" | \
    ssh "${ssh_opts[@]}" "$host" 'tar -xf - -C C:/ezc' 2>/dev/null || {
      # Windows OpenSSH has tar.exe since Win10 1803; if it is missing, fall back
      # to a per-file scp loop.
      ssh "${ssh_opts[@]}" "$host" 'if not exist C:\ezc\fixtures mkdir C:\ezc\fixtures'
      scp "${ssh_opts[@]}" "$fixtures"/* "$host:C:/ezc/fixtures/"
    }

  echo "--- windows leg ---"
  # shellcheck disable=SC2086
  ssh "${ssh_opts[@]}" "$host" \
    "C:\\ezc\\ezc-c3-e2e.exe C:\\ezc\\fixtures C:\\ezc\\work --soffice-dir=\"C:\\Program Files\\LibreOffice\\program\" ${args[*]:-}"
}

case "$leg" in
  linux) run_linux ;;
  windows) run_windows ;;
  *) echo "unknown leg: $leg" >&2; exit 2 ;;
esac
