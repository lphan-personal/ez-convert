#!/usr/bin/env bash
# Build and run the C2 media end-to-end matrix against real engines.
#
# The repo crate cannot be built on this box (Tauri needs GTK/WebKit), so this
# wraps the engine layer in a throwaway cargo crate whose only dependency is
# `lofty`, which `engine/tags.rs` needs and which the std-only rustc harness
# (`scripts/test-engine.sh`) stubs out.
#
# Engines (must be real):
#   EZC_VIPS_DIR         directory containing `vips` and `vipsheader`
#   EZC_FFMPEG_DIR       directory containing `ffmpeg` and `ffprobe`
#   EZC_ENGINE_LIB_DIR   optional: shared-library dir for a non-system vips
#
# Usage: spikes/c2/run-e2e.sh [fixtures-dir] [work-dir]
set -euo pipefail

repo_root="$(cd "$(dirname "${BASH_SOURCE[0]}")/../.." && pwd)"
src="$repo_root/src-tauri/src"
fixtures="${1:-$repo_root/fixtures}"
work="${2:-${TMPDIR:-/tmp}/ezc-c2-e2e}"

: "${EZC_VIPS_DIR:?set EZC_VIPS_DIR to the directory holding vips and vipsheader}"
: "${EZC_FFMPEG_DIR:?set EZC_FFMPEG_DIR to the directory holding ffmpeg and ffprobe}"

crate_dir="${TMPDIR:-/tmp}/ezc-c2-e2e-crate"
mkdir -p "$crate_dir/src"
cat >"$crate_dir/Cargo.toml" <<'EOF'
[package]
name = "ezc-c2-e2e"
version = "0.0.0"
edition = "2021"
publish = false

[dependencies]
lofty = "0.22"

[workspace]
EOF

cat >"$crate_dir/src/main.rs" <<EOF
// Generated by spikes/c2/run-e2e.sh — do not commit.
pub mod model {
    #[path = "$src/model/types.rs"]
    pub mod types;
    #[path = "$src/model/detect.rs"]
    pub mod detect;
    #[path = "$src/model/test_support.rs"]
    pub mod test_support;
    #[path = "$src/model/matrix.rs"]
    pub mod matrix;
}
#[path = "$src/engine/mod.rs"]
pub mod engine;

include!("$repo_root/spikes/c2/e2e.rs");
EOF

export PATH="$HOME/.cargo/bin:$PATH"
cd "$crate_dir"
cargo build --quiet
exec ./target/debug/ezc-c2-e2e "$fixtures" "$work"
